#!/usr/bin/env python3
"""Write the PPDs for the Beeprt-made Polono models (PL70e-BT, PL420).

Usage: python3 ppd/make_beeprt_ppds.py      (from the repository root)

Label sizes and option keywords follow Polono's own PPDs on purpose, so
printers switched over from Polono's driver keep their saved settings.
Only options whose output matches Polono's driver exactly are offered
(docs/TSPL.md). Edit this script, not the generated PPDs.
"""

PL70E_SIZES = [
    (283, 425), (90, 90), (108, 90), (108, 108), (108, 144), (144, 90), (144, 144),
    (144, 288), (144, 396), (161, 90), (161, 161), (161, 288), (161, 396), (171, 396),
    (180, 90), (180, 144), (198, 90), (216, 90), (216, 144), (216, 216), (216, 360),
    (234, 144), (234, 360), (234, 396), (234, 419), (234, 531), (288, 144), (288, 180),
    (288, 216), (288, 288), (288, 432), (288, 468), (288, 576), (288, 792), (288, 936),
    (138, 141), (141, 85), (141, 113), (170, 113), (212, 283), (209, 368), (223, 382),
    (283, 510), (283, 566), (209, 510), (226, 226), (215, 300), (212, 317),
]

PL420_SIZES = [
    (283, 425), (72, 144), (144, 288), (162, 90), (162, 288), (216, 144), (288, 288),
    (288, 432), (141, 85), (283, 510), (283, 566), (212, 317), (210, 510), (215, 300),
    (51, 164), (212, 280), (139, 141), (227, 227),
]


def label(w, h):
    """A readable size name: inches when both sides are on a quarter inch."""
    def inch(p):
        q = round(p / 18) * 18
        return q / 72 if q and abs(p - q) <= 1.5 else None
    wi, hi = inch(w), inch(h)
    if wi and hi:
        return f"{wi:g} x {hi:g} in"
    return f"{round(w * 25.4 / 72)} x {round(h * 25.4 / 72)} mm"


def pick_one(o, kw, title, order, default, choices):
    o.append(f"*OpenUI *{kw}/{title}: PickOne")
    o.append(f"*OrderDependency: {order} AnySetup *{kw}")
    o.append(f"*Default{kw}: {default}")
    for value, text in choices:
        o.append(f'*{kw} {value}/{text}: ""')
    o.append(f"*CloseUI: *{kw}")
    o.append("")


def mm_steps(lo, hi):
    return [(v, f"{v:+d} mm" if v else "0 mm") for v in range(lo, hi + 1)]


def ppd(model):
    pl70e = model == "PL70e"
    name = "PL70e-BT" if pl70e else "PL420"
    sizes = PL70E_SIZES if pl70e else PL420_SIZES
    o = []
    p = o.append
    p('*PPD-Adobe: "4.3"')
    p(f"*% Open-source driver for the Polono {name} thermal label printer.")
    p("*% Not made, endorsed or supported by Polono. MIT licence, see LICENSE.")
    p("*% Generated by ppd/make_beeprt_ppds.py: edit that, not this file.")
    p("*% Option keywords and size names match Polono's own PPD on purpose, so")
    p("*% printers switched over from Polono's driver keep their saved settings.")
    p('*FormatVersion: "4.3"')
    p('*FileVersion: "1.0.0"')
    p("*LanguageVersion: English")
    p("*LanguageEncoding: ISOLatin1")
    p(f'*PCFileName: "{"PL70EOPN" if pl70e else "PL420OPN"}.PPD"')
    p('*Manufacturer: "Polono"')
    p(f'*Product: "({name})"')
    # The *Product of Polono's own PPD, so the installer can recognise it.
    p(f'*Product: "({"ShippingPrinter PL70e-BT" if pl70e else "Label Printer"})"')
    p(f'*ModelName: "Polono {name}"')
    p(f'*ShortNickName: "Polono {name} (open-source)"')
    p(f'*NickName: "Polono {name} (open-source driver)"')
    p("*% The USB device ID is a best guess: it has not been seen on a real printer.")
    p(f'*1284DeviceID: "MFG:{"ShippingPrinter" if pl70e else "Label Printer"};MDL:{name};CMD:TSPL;"')
    p(f'*PolonoProfile: "{model}"')
    p('*PSVersion: "(3010.000) 0"')
    p('*LanguageLevel: "3"')
    p("*ColorDevice: False")
    p("*DefaultColorSpace: Gray")
    p("*FileSystem: False")
    p('*Throughput: "1"')
    p(f"*LandscapeOrientation: {'Minus90' if pl70e else 'Plus90'}")
    p("*TTRasterizer: Type42")
    p("*cupsVersion: 1.5")
    p("*% macOS makes the copies: the printer gets each label as its own page.")
    p("*cupsManualCopies: True")
    p('*cupsFilter: "application/vnd.cups-raster 100 rastertotspl"')
    p("")
    p("*% 4.08 in (104 mm) maximum width, 78.75 in maximum length.")
    p('*MaxMediaWidth: "294"')
    p('*MaxMediaHeight: "5670"')
    p("*HWMargins: 0 0 0 0")
    p('*CustomPageSize True: "pop pop pop <</PageSize[5 -2 roll]/ImagingBBox null>>setpagedevice"')
    p("*ParamCustomPageSize Width: 1 points 36 294")
    p("*ParamCustomPageSize Height: 2 points 36 5670")
    p("*ParamCustomPageSize WidthOffset: 3 points 0 0")
    p("*ParamCustomPageSize HeightOffset: 4 points 0 0")
    p("*ParamCustomPageSize Orientation: 5 int 0 0")
    p("*RequiresPageRegion All: True")
    p("")
    p("*OpenGroup: General/General")
    p("")
    for kw in ("PageSize", "PageRegion"):
        p(f"*OpenUI *{kw}/Label Size: PickOne")
        p(f"*OrderDependency: 10 AnySetup *{kw}")
        p(f"*Default{kw}: w283h425")
        for w, h in sizes:
            p(f'*{kw} w{w}h{h}/{label(w, h)}: "<</PageSize[{w} {h}]/ImagingBBox null>>setpagedevice"')
        p(f"*CloseUI: *{kw}")
        p("")
    p("*DefaultImageableArea: w283h425")
    for w, h in sizes:
        p(f'*ImageableArea w{w}h{h}: "0 0 {w} {h}"')
    p("")
    p("*DefaultPaperDimension: w283h425")
    for w, h in sizes:
        p(f'*PaperDimension w{w}h{h}: "{w} {h}"')
    p("")
    p("*CloseGroup: General")
    p("")
    p("*OpenGroup: Quality/Quality")
    p("")
    p("*OpenUI *Resolution/Resolution: PickOne")
    p("*OrderDependency: 10 AnySetup *Resolution")
    p("*DefaultResolution: 203dpi")
    p('*Resolution 203dpi/203 dpi: "<</HWResolution[203 203]/cupsBitsPerColor 8/cupsRowCount 8/cupsRowFeed 0/cupsRowStep 0/cupsColorSpace 0>>setpagedevice"')
    p("*CloseUI: *Resolution")
    p("")
    if pl70e:
        p("*% Threshold applies only with Image Filter = black and white.")
        pick_one(o, "ImageFilter", "Image Filter", 160, 0, [
            (0, "Black and white (threshold)"), (1, "Floyd-Steinberg dithering"),
            (3, "Burkes dithering"), (4, "Stucki dithering"), (5, "Jarvis-Judice-Ninke dithering"),
            (6, "Sierra dithering"), (7, "Stevenson-Arce dithering"), (2, "Ordered dithering 4 x 4"),
            (8, "Bayer 4 x 4"), (9, "Bayer 8 x 8"), (10, "Bayer 16 x 16")])
        p("*% A dot prints when its grey level (0 = black, 255 = white), after")
        p("*% Brightness, is at or below this value.")
        pick_one(o, "Threshold", "Black Threshold", 160, 175, [
            (t, f"{t}{' (only pure black prints)' if t == 0 else ' (everything prints)' if t == 255 else ' (default)' if t == 175 else ''}")
            for t in range(256)])
        pick_one(o, "Brightness", "Brightness", 160, 0, [
            (b, f"{b:+d}{' (lighter)' if b == 255 else ' (darker)' if b == -255 else ''}" if b else "0")
            for b in range(-255, 256)])
    else:
        p("*% A dot prints when it is at least 22% grey (raster value 200 or less, 0 = black).")
    p("*CloseGroup: Quality")
    p("")
    p("*OpenGroup: PrinterSettings/Printer Settings")
    p("")
    media = [("Gap", "Labels with gaps"), ("BLine", "Labels with black marks"), ("Continuous", "Continuous roll")]
    if not pl70e:
        # Polono's PL420 driver sends gap sensing for "Black Line" too, so
        # that choice is left out rather than offered under a false name.
        media = [m for m in media if m[0] != "BLine"]
    pick_one(o, "zeMediaTracking", "Media Type", 20, "Gap", media)
    pick_one(o, "Darkness", "Darkness", 20, 8, [("Default", "Printer setting")] + [
        (d, f"{d}{' (lightest)' if d == 0 else ' (darkest)' if d == 15 else ''}") for d in range(16)])
    pick_one(o, "zePrintRate", "Print Speed", 20, "Default" if pl70e else 8,
             [("Default", "Printer setting")] + [(s, f"{s} in/s") for s in range(1, 9)])
    p("*CloseGroup: PrinterSettings")
    p("")
    p("*OpenGroup: PageSet/Page Options")
    p("")
    if pl70e:
        p("*% Rotate numbering is Polono's: 1 = 180 degrees, 2 = 90, 3 = 270.")
        pick_one(o, "Rotate", "Rotation", 160, 0, [
            (0, "None"), (2, "90 degrees anticlockwise"), (1, "180 degrees"), (3, "90 degrees clockwise")])
    else:
        p("*% Sent to the printer as DIRECTION n,0. Polono's default is 1.")
        pick_one(o, "Rotate", "Print Direction", 160, 1, [
            (1, "Normal (Polono's default)"), (0, "Turned 180 degrees"), (2, "Direction 2"), (3, "Direction 3")])
    p("*% \"AdjustHoriaontal\" (sic) is Polono's keyword, kept so saved settings carry over.")
    if pl70e:
        # Polono's PPD calls these steps millimetres, but its driver moves
        # the print 64 dots (8 mm) per step, so the labels say so.
        p("*% Each step moves the print 64 dots (8 mm).")
        adjust = [(v, f"{v * 8:+d} mm" if v else "0 mm") for v in range(-20, 21)]
    else:
        p("*% Each step moves the print 8 dots (1 mm).")
        adjust = mm_steps(-20, 20)
    pick_one(o, "AdjustHoriaontal", "Horizontal Offset", 130, 0, adjust)
    pick_one(o, "AdjustVertical", "Vertical Offset", 130, 0, adjust)
    pick_one(o, "FeedOffset", "Stop Position Offset", 160, 0, mm_steps(-20, 20))
    pick_one(o, "AutoDotted", "Dotted Line Between Labels", 160, 0, [(0, "No"), (1, "Yes")])
    p("*CloseGroup: PageSet")
    return "\n".join(o) + "\n"


if __name__ == "__main__":
    for model in ("PL70e", "PL420"):
        with open(f"ppd/{model}-open-source.ppd", "w", encoding="latin-1") as f:
            f.write(ppd(model))
